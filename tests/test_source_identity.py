"""A failed fetch keeps the previous names or synced examples only if they came from the same source.

Otherwise a dataset moved to another endpoint (or curator repository) would keep resolving
names to, and retrieving examples of, the old one.
"""

import json

import pytest

from sparql_llm.indexing import sync_examples
from sparql_llm.indexing.entity_names import build_entity_names
from sparql_llm.indexing.sync_examples import sync_curator_examples


def _broken(query, endpoint, **kwargs):
    raise TimeoutError("endpoint down")


def test_names_from_another_endpoint_are_not_kept(swiss_project):
    target = swiss_project.entity_names_path
    old_source = {"endpoint": "https://old.example/sparql", "graphs": [], "entities": {}}
    target.write_text(
        json.dumps({"source": old_source, "entities": [{"uri": "https://old.example/person/1", "label": "Weber", "type": "Person"}]}),
        encoding="utf-8",
    )

    report = build_entity_names(swiss_project, fetch=_broken)

    payload = json.loads(target.read_text(encoding="utf-8"))
    assert payload["entities"] == []
    assert payload["source"]["endpoint"] == swiss_project.endpoint_url
    assert "another source" in report["error"]


def _synced_file(repo: str, endpoint: str | None) -> str:
    endpoint_line = f"     Endpoint: {endpoint}\n" if endpoint else ""
    return (
        "<!-- Generated by sparql_llm.indexing.sync_examples — do not edit.\n"
        f"     Source of truth: {repo}, llm_documentation/SPARQL_queries_examples/\n"
        f"{endpoint_line}"
        "     Every query below was executed against the endpoint before being written. -->\n\n"
        "# Old\n\n## Example 1: Old\n\nQuestion: Old question?\n\n```sparql\nSELECT * WHERE { ?s ?p ?o }\n```\n"
    )


@pytest.fixture
def sync_fails(monkeypatch: pytest.MonkeyPatch):
    monkeypatch.setattr(sync_examples, "discover_sources", lambda config, client: ((), "listing failed"))


def test_synced_examples_from_another_endpoint_are_not_kept(swiss_project, sync_fails):
    target = swiss_project.synced_examples_path
    target.write_text(_synced_file("lod4hss-projects/elites-suisses", "https://old.example/sparql"), encoding="utf-8")

    report = sync_curator_examples(swiss_project)

    assert "Old question" not in target.read_text(encoding="utf-8")
    assert f"Endpoint: {swiss_project.endpoint_url}" in target.read_text(encoding="utf-8")
    assert "another source" in report["error"]


def test_synced_examples_from_another_repository_are_not_kept(swiss_project, sync_fails):
    target = swiss_project.synced_examples_path
    target.write_text(_synced_file("someone/else", None), encoding="utf-8")
    sync_curator_examples(swiss_project)
    assert "Old question" not in target.read_text(encoding="utf-8")


def test_synced_examples_from_the_same_source_are_kept(swiss_project, sync_fails):
    target = swiss_project.synced_examples_path
    # Files written before the endpoint was recorded name only the repository.
    target.write_text(_synced_file("lod4hss-projects/elites-suisses", None), encoding="utf-8")
    report = sync_curator_examples(swiss_project)
    assert "Old question" in target.read_text(encoding="utf-8")
    assert "previously synced examples are kept" in report["error"]


def test_a_successful_sync_records_the_endpoint(swiss_project, monkeypatch: pytest.MonkeyPatch):
    monkeypatch.setattr(sync_examples, "discover_sources", lambda config, client: (("https://x/a.md",), ""))
    monkeypatch.setattr(sync_examples, "fetch", lambda url, client: "")
    monkeypatch.setattr(sync_examples, "validate", lambda parsed, endpoint, post: ([], []))
    sync_curator_examples(swiss_project)
    assert f"Endpoint: {swiss_project.endpoint_url}" in swiss_project.synced_examples_path.read_text(encoding="utf-8")

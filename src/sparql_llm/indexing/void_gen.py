"""Generate a project's VoID description from its endpoint.

Queries the endpoint for:
- Total triples / entities
- Per-class instance counts (void:classPartition)
- Per-(class, predicate) counts (void:classPartition / void:propertyPartition)
- Overall predicate counts (void:propertyPartition)

and writes ``data/<id>/void.ttl``. SparqlVoidShapesLoader consumes it to build the class
shapes that the validator and the system prompt benefit from. Run by every admin rebuild;
``scripts/enrich_void.py`` is a command-line wrapper for developers.

The file is written atomically and parsed back before it replaces the previous one: a
schema that cannot be read must stop the rebuild, not leave the assistant with no schema.
"""

from __future__ import annotations

import os
from collections.abc import Callable
from typing import Any

import rdflib

from sparql_llm.project import Project, SchemaClasses, graph_pattern, shorten
from sparql_llm.utils import logger, query_sparql


class VoidError(Exception):
    """The generated VoID could not be read back. The message is meant for the admin page."""


#: Classes that describe the service rather than the data; never part of the schema.
SERVICE_CLASSES: frozenset[str] = frozenset(
    {
        "http://rdfs.org/ns/void#Dataset",
        "http://www.w3.org/ns/sparql-service-description#Service",
        "http://www.w3.org/ns/sparql-service-description#Dataset",
        "http://www.w3.org/ns/sparql-service-description#Graph",
        "http://www.w3.org/ns/sparql-service-description#NamedGraph",
        "http://www.w3.org/ns/dcat#Dataset",
    }
)

#: Prefixes the generated file itself needs, added when the project does not declare them.
_OWN_PREFIXES = {
    "void": "http://rdfs.org/ns/void#",
    "xsd": "http://www.w3.org/2001/XMLSchema#",
    "rdf": "http://www.w3.org/1999/02/22-rdf-syntax-ns#",
}

def keep_class(iri: str, count: int, cfg: SchemaClasses) -> bool:
    """Whether a class belongs in the schema: not a service class, enough instances, not excluded."""
    if iri in SERVICE_CLASSES or count < cfg.min_instances:
        return False
    return not any(iri.startswith(prefix) for prefix in cfg.exclude)


def generate_void(project: Project, fetch: Callable[..., Any] = query_sparql) -> dict[str, Any]:
    """Query the endpoint, write ``project.void_path`` and return the statistics."""
    endpoint = project.endpoint_url
    post = project.method == "POST"

    def select(where: str, head: str, tail: str = "") -> list[dict[str, Any]]:
        query = f"SELECT {head} WHERE {{ {graph_pattern(project.graphs, where)} }} {tail}".strip()
        return fetch(query, endpoint, post=post, timeout=300)["results"]["bindings"]

    triples = int(select("?s ?p ?o", "(COUNT(*) AS ?n)")[0]["n"]["value"])
    entities = int(select("?s ?p ?o", "(COUNT(DISTINCT ?s) AS ?n)")[0]["n"]["value"])
    all_classes = [
        (r["c"]["value"], int(r["n"]["value"]))
        for r in select("?s a ?c", "?c (COUNT(*) AS ?n)", "GROUP BY ?c ORDER BY DESC(?n)")
    ]
    props = [
        (r["p"]["value"], int(r["n"]["value"]))
        for r in select("?s ?p ?o", "?p (COUNT(*) AS ?n)", "GROUP BY ?p ORDER BY DESC(?n)")
    ]
    by_class: dict[str, list[tuple[str, int]]] = {}
    for r in select("?s a ?c ; ?p ?o", "?c ?p (COUNT(*) AS ?n)", "GROUP BY ?c ?p ORDER BY ?c DESC(?n)"):
        by_class.setdefault(r["c"]["value"], []).append((r["p"]["value"], int(r["n"]["value"])))

    classes = [(c, n) for c, n in all_classes if keep_class(c, n, project.schema_classes)]
    prefixes = {**_OWN_PREFIXES, **project.prefixes}

    def short(iri: str) -> str:
        return shorten(iri, prefixes)

    lines = [
        "# Generated by the admin rebuild (sparql_llm.indexing.void_gen) — do not edit by hand.",
        f"# Source endpoint: {endpoint}",
        "",
    ]
    lines += [f"@prefix {p}: <{ns}> ." for p, ns in prefixes.items()]
    lines += [
        "",
        f"<{endpoint}#void> a void:Dataset ;",
        f'    void:triples "{triples}"^^xsd:integer ;',
        f'    void:entities "{entities}"^^xsd:integer ;',
        f"    void:sparqlEndpoint <{endpoint}> ;",
    ]
    if classes:
        lines.append(f"    void:classes {', '.join(short(c) for c, _ in classes)} ;")
    if props:
        lines.append(f"    void:properties {', '.join(short(p) for p, _ in props)} ;")
    for c, n in classes:
        lines.append("    void:classPartition [")
        lines.append(f"        void:class {short(c)} ;")
        lines.append(f'        void:entities "{n}"^^xsd:integer ;')
        cprops = by_class.get(c, [])
        for i, (p, pn) in enumerate(cprops):
            lines.append("        void:propertyPartition [")
            lines.append(f"            void:property {short(p)} ;")
            lines.append(f'            void:triples "{pn}"^^xsd:integer')
            lines.append("        ]" + (" ;" if i < len(cprops) - 1 else ""))
        lines.append("    ] ;")
    for p, n in props:
        lines.append("    void:propertyPartition [")
        lines.append(f"        void:property {short(p)} ;")
        lines.append(f'        void:triples "{n}"^^xsd:integer')
        lines.append("    ] ;")
    # Close the dataset description: replace the last " ;" with " ."
    lines[-1] = lines[-1][: -len(" ;")] + " ."

    path = project.void_path
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f"{path.name}.tmp{os.getpid()}")
    tmp.write_text("\n".join(lines) + "\n", encoding="utf-8")
    try:
        rdflib.Graph().parse(tmp, format="turtle")
    except Exception as exc:
        tmp.unlink(missing_ok=True)
        reason = str(exc).splitlines()[0][:200] if str(exc) else type(exc).__name__
        raise VoidError(f"The generated schema for {project.label} could not be read back: {reason}") from exc
    os.replace(tmp, path)

    report = {
        "triples": triples,
        "entities": entities,
        "classes_total": len(all_classes),
        "classes_kept": len(classes),
        "predicates": len(props),
    }
    logger.info("Wrote %s: %s", path, report)
    return report

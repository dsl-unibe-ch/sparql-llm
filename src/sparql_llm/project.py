"""One SPARQL endpoint per project: its settings live in ``<data_dir>/<id>/project.json``.

The install settings list the project ids this instance serves (``settings.projects``).
Every module asks this registry for the endpoint entries instead of hard-coding a dataset.

Three states of a project's files, so nothing unchecked is ever served:
- live, in ``<data_dir>/<id>/``: what the instance serves, also after a restart;
- uploaded, in ``<id>/uploaded/``: what a curator uploaded and Check / Rebuild test;
- next, in ``<id>/next/``: what a running rebuild generates.
A successful rebuild promotes uploaded and next into live together; a failed one discards next.
"""

from __future__ import annotations

import json
import logging
import os
import re
import shutil
from pathlib import Path
from typing import TYPE_CHECKING, Literal

from pydantic import BaseModel, ConfigDict, Field, PrivateAttr, ValidationError, field_validator

if TYPE_CHECKING:
    from sparql_llm.config import SparqlEndpointLinks

PROJECT_FILE = "project.json"
UPLOADED_DIR = "uploaded"
BUILD_DIR = "next"
#: Generated by a rebuild; promoted from next/ into the live folder.
GENERATED_FILES = ("void.ttl", "prefixes.json", "entity_names.json", "fingerprint.json", "examples-synced.md")


class ProjectError(Exception):
    """A project file is missing or invalid. The message names the file and the field to fix."""


class EntityType(BaseModel):
    model_config = ConfigDict(populate_by_name=True)

    class_iri: str = Field(alias="class")
    birth_property: str | None = None
    death_property: str | None = None


class EntityConfig(BaseModel):
    label_property: str
    types: dict[str, EntityType]


class SchemaClasses(BaseModel):
    min_instances: int = 1
    exclude: list[str] = []


class CuratorExamples(BaseModel):
    github_repo: str
    folder: str
    branch: str = "main"


class Project(BaseModel):
    """One endpoint entry, as written in project.json."""

    id: str = Field(pattern=r"^[a-z0-9][a-z0-9-]*$")
    label: str
    endpoint_url: str
    method: Literal["GET", "POST"] = "GET"
    description: str = ""
    homepage_url: str | None = None
    graphs: list[str] = []
    prefixes: dict[str, str] = {}
    dataset_description_file: str = "dataset.md"
    examples_file: str = "examples.md"
    entities: EntityConfig | None = None
    schema_classes: SchemaClasses = SchemaClasses()
    curator_examples: CuratorExamples | None = None
    prefix_repairs: dict[str, str] = {}
    ontology_from_endpoint: bool = False

    _data_dir: Path = PrivateAttr(default=Path("data"))
    #: A candidate reads uploaded files over live ones and writes generated files to next/.
    _candidate: bool = PrivateAttr(default=False)

    @field_validator("dataset_description_file", "examples_file")
    @classmethod
    def _bare_markdown_name(cls, value: str) -> str:
        # Read into every prompt: a path out of the project folder could expose server files.
        if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]*\.md", value) or ".." in value:
            raise ValueError("must be a file name in the project folder ending in .md, e.g. dataset.md")
        return value

    @field_validator("endpoint_url", "homepage_url")
    @classmethod
    def _http_url(cls, value: str | None) -> str | None:
        if value is not None and not re.match(r"https?://[^\s]+$", value):
            raise ValueError("must be an http:// or https:// address")
        return value

    @property
    def dir(self) -> Path:
        return self._data_dir / self.id

    @property
    def uploaded_dir(self) -> Path:
        return self.dir / UPLOADED_DIR

    @property
    def build_dir(self) -> Path:
        return self.dir / BUILD_DIR

    def _source(self, name: str) -> Path:
        uploaded = self.uploaded_dir / name
        return uploaded if self._candidate and uploaded.is_file() else self.dir / name

    def _generated(self, name: str) -> Path:
        return (self.build_dir if self._candidate else self.dir) / name

    @property
    def void_path(self) -> Path:
        return self._generated("void.ttl")

    @property
    def prefixes_path(self) -> Path:
        return self._generated("prefixes.json")

    @property
    def entity_names_path(self) -> Path:
        return self._generated("entity_names.json")

    @property
    def synced_examples_source(self) -> Path:
        """The synced examples to index: this rebuild's if the sync wrote them, else the live ones."""
        built = self.synced_examples_path
        return built if built.is_file() else self.dir / "examples-synced.md"

    @property
    def live_entity_names_path(self) -> Path:
        return self.dir / "entity_names.json"

    @property
    def fingerprint_path(self) -> Path:
        return self._generated("fingerprint.json")

    @property
    def synced_examples_path(self) -> Path:
        return self._generated("examples-synced.md")

    @property
    def dataset_path(self) -> Path:
        return self._source(self.dataset_description_file)

    @property
    def examples_path(self) -> Path:
        return self._source(self.examples_file)

    @property
    def upload_log_path(self) -> Path:
        return self.dir / "uploads.json"

    def as_endpoint_links(self) -> SparqlEndpointLinks:
        return {
            "endpoint_url": self.endpoint_url,
            "label": self.label,
            "description": self.description,
            "homepage_url": self.homepage_url,
            "void_file": str(self.void_path),
            "examples_file": str(self.examples_path),
        }


#: A Turtle local name we can write safely: no slash, no trailing dot.
_LOCAL_NAME = re.compile(r"^[A-Za-z0-9_](?:[A-Za-z0-9_.%-]*[A-Za-z0-9_%-])?$")


def shorten(iri: str, prefixes: dict[str, str]) -> str:
    """A prefixed name when the longest matching namespace leaves a valid local name, else <iri>."""
    best = ""
    best_ns = ""
    for prefix, ns in prefixes.items():
        if iri.startswith(ns) and len(ns) > len(best_ns):
            best, best_ns = prefix, ns
    local = iri[len(best_ns) :]
    if best_ns and _LOCAL_NAME.match(local):
        return f"{best}:{local}"
    return f"<{iri}>"


def label_property_names(projects: list[Project] | None = None) -> str:
    """The configured name/label properties as prefixed names, for prompts and fallback hints."""
    names = []
    for project in get_projects() if projects is None else projects:
        if project.entities:
            name = shorten(project.entities.label_property, project.prefixes)
            if name not in names:
                names.append(name)
    return " or ".join(names) or "the label property (rdfs:label)"


def graph_pattern(graphs: list[str], pattern: str) -> str:
    """Wrap a triple pattern for the project's graphs: none = default graph, one, or several."""
    if not graphs:
        return pattern
    if len(graphs) == 1:
        return f"GRAPH <{graphs[0]}> {{ {pattern} }}"
    values = " ".join(f"<{g}>" for g in graphs)
    return f"GRAPH ?g {{ {pattern} }} VALUES ?g {{ {values} }}"


def describe_validation_error(err: ValidationError) -> list[str]:
    """Pydantic errors as plain ``"<field>: <reason>"`` lines."""
    lines = []
    for e in err.errors():
        field = ".".join(str(part) for part in e["loc"]) or "file"
        lines.append(f"{field}: {e['msg']}")
    return lines


def load_project(data_dir: Path, project_id: str, candidate: bool = False) -> Project:
    """The live project; with ``candidate``, the uploaded files where there are any."""
    path = Path(data_dir) / project_id / PROJECT_FILE
    if candidate and (path.parent / UPLOADED_DIR / PROJECT_FILE).is_file():
        path = path.parent / UPLOADED_DIR / PROJECT_FILE
    if not path.is_file():
        raise ProjectError(f"The project file {path} for project '{project_id}' is missing.")
    try:
        content = json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, UnicodeDecodeError) as e:
        raise ProjectError(f"The project file {path} is not valid JSON: {e}") from e
    try:
        project = Project.model_validate(content)
    except ValidationError as e:
        raise ProjectError(f"The project file {path} has errors: " + "; ".join(describe_validation_error(e))) from e
    if project.id != project_id:
        raise ProjectError(
            f"The project file {path} says id '{project.id}', but it is in the folder of project '{project_id}'. "
            "The id must match the folder name."
        )
    project._data_dir = Path(data_dir)
    project._candidate = candidate
    return project


_projects: list[Project] | None = None
_problems: dict[str, str] = {}


def read_projects(candidates: bool = False) -> tuple[list[Project], dict[str, str]]:
    """Read every project listed in the install settings from disk, without serving them.

    Returns the valid projects and, per project id, why its file could not be used. A
    missing or broken project file must not stop the instance: its admin page is where
    the curator uploads the fix. ``candidates`` reads the uploaded files over the live ones,
    as Check and Rebuild do.
    """
    from sparql_llm.config import settings

    projects: list[Project] = []
    problems: dict[str, str] = {}
    for pid in settings.projects:
        try:
            projects.append(load_project(Path(settings.data_dir), pid, candidate=candidates))
        except ProjectError as e:
            problems[pid] = str(e)
    return projects, problems


def discard_build(project: Project) -> None:
    """Drop what an unfinished rebuild generated; the live files were never touched."""
    shutil.rmtree(project.build_dir, ignore_errors=True)


def promote(project: Project) -> None:
    """Make a rebuilt candidate live: generated files from next/, then the uploaded files.

    Each replaced uploaded file is kept as ``<name>.prev`` for Undo. Generated files the
    project no longer configures (entity names, synced examples) are removed.
    """
    live = project.dir
    for name in GENERATED_FILES:
        built = project.build_dir / name
        if built.is_file():
            os.replace(built, live / name)
    if project.entities is None:
        (live / "entity_names.json").unlink(missing_ok=True)
    if project.curator_examples is None:
        (live / "examples-synced.md").unlink(missing_ok=True)
    if project.uploaded_dir.is_dir():
        for uploaded in project.uploaded_dir.iterdir():
            if not uploaded.is_file():
                continue
            target = live / uploaded.name
            if target.exists():
                os.replace(target, live / f"{uploaded.name}.prev")
            os.replace(uploaded, target)
        shutil.rmtree(project.uploaded_dir, ignore_errors=True)
    discard_build(project)


def reload_projects() -> list[Project]:
    """Serve the project files as they are on disk now."""
    global _projects, _problems
    from sparql_llm.migration import migrate_configured

    # Before anything reads a project folder: the validator metadata loads at import time.
    migrate_configured()
    _projects, _problems = read_projects()
    for message in _problems.values():
        logging.getLogger("sparql_llm").error(message)
    return _projects


def project_problems() -> dict[str, str]:
    """Per project id, why its project file is not being served (empty when all are fine)."""
    get_projects()
    return dict(_problems)


def get_projects() -> list[Project]:
    if _projects is None:
        return reload_projects()
    return _projects


def allowed_endpoint(url: str | None) -> tuple[str | None, str]:
    """The endpoint a query may run on, and a note when it is not the one asked for.

    Queries only ever run on configured endpoints. With one project an unknown or missing
    URL can only mean that endpoint; with several there is no safe guess.
    """
    urls = [p.endpoint_url for p in get_projects()]
    if url and url in urls:
        return url, ""
    if len(urls) == 1:
        return urls[0], f"Ran on {urls[0]}, the configured endpoint, instead of {url or 'no endpoint'}."
    if not urls:
        return None, "No endpoint is configured for this instance."
    return None, f"Unknown endpoint {url}. Use one of: {', '.join(urls)}."


def post_for(endpoint_url: str | None) -> bool:
    """Whether queries to this endpoint go by POST, as its project says (GET when unknown)."""
    return any(p.endpoint_url == endpoint_url and p.method == "POST" for p in get_projects())


def get_project(project_id: str) -> Project:
    for project in get_projects():
        if project.id == project_id:
            return project
    raise ProjectError(f"Project '{project_id}' is not served by this instance.")
